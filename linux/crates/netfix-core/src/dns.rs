    #[test]
    fn test_reset_nmcli_entries_continues_after_first_entry_failure() {
        let dir = tempfile::tempdir().unwrap();
        let backup_path = dir.path().join("dns-nmcli-backup.json");
        let backups = vec![
            NmcliConnBackup {
                uuid: "missing-uuid".into(),
                ipv4_dns: String::new(),
                ipv4_ignore_auto_dns: "no".into(),
                ipv6_dns: String::new(),
                ipv6_ignore_auto_dns: "no".into(),
            },
            NmcliConnBackup {
                uuid: "valid-uuid".into(),
                ipv4_dns: "192.168.1.1".into(),
                ipv4_ignore_auto_dns: "yes".into(),
                ipv6_dns: String::new(),
                ipv6_ignore_auto_dns: String::new(),
            },
        ];
        std::fs::write(&backup_path, serde_json::to_vec(&backups).unwrap()).unwrap();

        let mut calls: Vec<Vec<String>> = Vec::new();
        let err = reset_nmcli_backup_file(&backup_path, |args| {
            calls.push(args.iter().map(|s| (*s).to_string()).collect());
            if args.contains(&"missing-uuid") {
                return Err(NetfixError::Runtime("Unknown connection".into()));
            }
            Ok(())
        })
        .unwrap_err();

        assert!(err.to_string().contains("missing-uuid"));
        assert!(!backup_path.exists());
        assert!(calls.iter().any(|c| c == &vec![
            "con",
            "mod",
            "valid-uuid",
            "ipv4.dns",
            "192.168.1.1",
            "ipv4.ignore-auto-dns",
            "yes",
            "ipv6.dns",
            "",
            "ipv6.ignore-auto-dns",
            "no",
        ]));
        assert!(calls
            .iter()
            .any(|c| c == &vec!["con", "up", "valid-uuid"]));
    }
